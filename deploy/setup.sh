#!/usr/bin/env bash
# DEPLOY-01 — one-time setup of a fresh Ubuntu 24.04 server (docs/15-deployment.md). Run as root from the clone:
#   bash /opt/tradingworld/deploy/setup.sh trading.mediatechnologies.uk
# Safe to run again: existing secrets, keys and the admin account are kept.
set -euo pipefail

main() {
  DOMAIN="${1:-}"
  [ -n "$DOMAIN" ] || { echo "usage: setup.sh DOMAIN   (e.g. trading.mediatechnologies.uk)"; exit 2; }
  [ "$(id -u)" = 0 ] || { echo "run as root"; exit 2; }
  grep -q 'VERSION_ID="24.04"' /etc/os-release || echo "warning: written for Ubuntu 24.04"
  DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  ROOT="$(dirname "$DIR")"
  ENV="$DIR/.env"
  say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

  say "packages: Docker, Compose, firewall, fail2ban, age"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq docker.io docker-compose-v2 docker-buildx git ufw fail2ban age openssl curl >/dev/null
  # container logs rotate instead of filling the disk
  if [ ! -f /etc/docker/daemon.json ]; then
    printf '{ "log-driver": "json-file", "log-opts": { "max-size": "10m", "max-file": "3" } }\n' >/etc/docker/daemon.json
  fi
  systemctl enable --now docker >/dev/null
  systemctl restart docker
  systemctl enable --now fail2ban >/dev/null

  say "swap (the web build needs 2-3 GB for a moment)"
  if [ -z "$(swapon --show)" ]; then
    fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
    grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >>/etc/fstab
    echo "4 GB swap added"
  else
    echo "swap already present"
  fi

  say "firewall: SSH, HTTP, HTTPS only"
  ufw allow OpenSSH >/dev/null
  ufw allow 80/tcp >/dev/null
  ufw allow 443/tcp >/dev/null
  ufw allow 443/udp >/dev/null
  ufw --force enable >/dev/null
  ufw status | head -12

  say "secrets (generated here, never leave this server)"
  mkdir -p "$DIR/secrets"
  chmod 700 "$DIR/secrets"
  if [ ! -f "$DIR/secrets/age-identity.txt" ]; then
    age-keygen -o "$DIR/secrets/age-identity.txt" 2>/dev/null
    chmod 600 "$DIR/secrets/age-identity.txt"
  fi
  AGE_RECIPIENT="$(age-keygen -y "$DIR/secrets/age-identity.txt")"
  if [ ! -f "$ENV" ]; then
    rand() { openssl rand -hex "$1"; }
    # Web Push (VAPID): a P-256 key pair; public = uncompressed point, private = the 32-byte scalar, both base64url
    b64url() { base64 -w0 | tr '+/' '-_' | tr -d '='; }
    openssl ecparam -name prime256v1 -genkey -noout -out /tmp/vapid.pem 2>/dev/null
    VAPID_PRIVATE="$(openssl ec -in /tmp/vapid.pem -outform DER 2>/dev/null | tail -c +8 | head -c 32 | b64url)"
    VAPID_PUBLIC="$(openssl ec -in /tmp/vapid.pem -pubout -outform DER 2>/dev/null | tail -c 65 | b64url)"
    rm -f /tmp/vapid.pem
    # trading.mediatechnologies.uk → mediatechnologies.uk (a domain with one dot stays as it is)
    BASE_DOMAIN="$DOMAIN"
    [ "$(echo "$DOMAIN" | tr -cd . | wc -c)" -ge 2 ] && BASE_DOMAIN="${DOMAIN#*.}"
    ADMIN_EMAIL="${ADMIN_EMAIL:-admin@$BASE_DOMAIN}"
    ADMIN_PASSWORD="$(openssl rand -base64 18 | tr '+/' '-_' | tr -d '=')"
    umask 077
    cat >"$ENV" <<EOF
# DEPLOY-01 — production settings for $DOMAIN. Generated by deploy/setup.sh on $(date -u +%F). Keep this file private.
DOMAIN=$DOMAIN
POSTGRES_PASSWORD=$(rand 24)
JWT_SECRET=$(rand 32)
METRICS_TOKEN=$(rand 24)

# admin account, created on first start; afterwards reset with: deploy/tw exec api node apps/api/dist/tools/admin.js reset-password EMAIL
ADMIN_EMAIL=$ADMIN_EMAIL
ADMIN_PASSWORD=$ADMIN_PASSWORD

# Web Push
VAPID_PUBLIC_KEY=$VAPID_PUBLIC
VAPID_PRIVATE_KEY=$VAPID_PRIVATE
VAPID_SUBJECT=mailto:$ADMIN_EMAIL

# backups: encrypted to this key (private half in deploy/secrets/age-identity.txt); add an offsite copy (docs/13)
BACKUP_AGE_RECIPIENTS=$AGE_RECIPIENT
BACKUP_RCLONE_REMOTE=

# market data: demo until a licensed provider is set (docs/03), e.g. MARKET_DATA_ROUTES=forex=twelvedata,metal=twelvedata
MARKET_DATA_PROVIDER=demo
MARKET_DATA_ROUTES=
TWELVEDATA_API_KEY=
POLYGON_API_KEY=

# email (off until set): smtps://user:pass@smtp.example.com:465
SMTP_URL=
EMAIL_FROM=TradingWorld <alerts@$BASE_DOMAIN>
# ops alerts to Slack/Discord/Teams (admins get them in the inbox regardless)
OPS_ALERT_WEBHOOK_URL=
EOF
    chmod 600 "$ENV"
    FIRST_PASSWORD="$ADMIN_PASSWORD"
    echo "deploy/.env written"
  else
    echo "deploy/.env exists, kept"
  fi

  say "DNS check"
  ip="$(curl -fsS -4 --max-time 5 https://api.ipify.org 2>/dev/null || true)"
  resolved="$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}')"
  if [ -n "$ip" ] && [ "$resolved" = "$ip" ]; then
    echo "$DOMAIN → $ip ✓"
  else
    echo "warning: $DOMAIN resolves to '${resolved:-nothing}', this server is '${ip:-unknown}'."
    echo "         Add an A record (Cloudflare: proxy OFF, grey cloud). HTTPS starts once it points here."
  fi

  say "first deploy (builds the images: about 5-10 minutes)"
  cd "$ROOT"
  git config --global --add safe.directory "$ROOT"
  "$DIR/deploy.sh" --force

  say "automatic updates: every 2 minutes from main"
  cat >/etc/systemd/system/tradingworld-deploy.service <<EOF
[Unit]
Description=TradingWorld: deploy the newest commit on main
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=$DIR/deploy.sh
EOF
  cat >/etc/systemd/system/tradingworld-deploy.timer <<EOF
[Unit]
Description=TradingWorld: check main for a new commit every 2 minutes

[Timer]
OnBootSec=2min
OnUnitActiveSec=2min

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  systemctl enable --now tradingworld-deploy.timer >/dev/null
  echo "timer on (logs: journalctl -u tradingworld-deploy -f)"

  say "done"
  "$DIR/tw" ps --format 'table {{.Service}}\t{{.Status}}'
  echo
  echo "  site   : https://$DOMAIN"
  echo "  admin  : $(grep '^ADMIN_EMAIL=' "$ENV" | cut -d= -f2)"
  if [ -n "${FIRST_PASSWORD:-}" ]; then
    echo "  password: $FIRST_PASSWORD"
    echo "  (shown once; it is also in deploy/.env until you remove the ADMIN_PASSWORD line)"
  fi
}

main "$@"
