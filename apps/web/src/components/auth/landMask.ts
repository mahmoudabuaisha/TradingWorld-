/** Unit vectors of the lattice points that are on land, as x, y, z triples (y up, longitude 0 facing +z). */
export function landPositions(): Float32Array {
  const bin = atob(MASK);
  const golden = Math.PI * (3 - Math.sqrt(5));
  const out: number[] = [];
  for (let i = 0; i < LAND_POINTS; i++) {
    if (!((bin.charCodeAt(i >> 3) >> (i & 7)) & 1)) continue;
    const y = 1 - (2 * (i + 0.5)) / LAND_POINTS;
    const r = Math.sqrt(1 - y * y);
    const lon = (i * golden) % (2 * Math.PI);
    out.push(r * Math.sin(lon), y, r * Math.cos(lon));
  }
  return new Float32Array(out);
}

/** Latitude and longitude in degrees to a unit vector in the same frame. */
export function fromLatLon(lat: number, lon: number): [number, number, number] {
  const la = (lat * Math.PI) / 180;
  const lo = (lon * Math.PI) / 180;
  return [Math.cos(la) * Math.sin(lo), Math.sin(la), Math.cos(la) * Math.cos(lo)];
}
